export function getSimpleIconUrl(slug: string, color?: string): string {
  const base = `https://cdn.simpleicons.org/${slug}`;
  return color ? `${base}/${color}` : base;
}

export function getSlugForDomain(domain: string): string | null {
  return DOMAIN_SLUG_MAP[domain.toLowerCase()] ?? null;
}

export function getSlugForUrl(url: string): string | null {
  try {
    const hostname = new URL(url).hostname.toLowerCase();
    return getSlugForDomain(hostname);
  } catch {
    return null;
  }
}

