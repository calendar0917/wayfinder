export function searchIcons(query: string): Array<{ slug: string; name: string }> {
  if (!query.trim()) return SEARCHABLE_ICONS.slice(0, 20);
  const q = query.toLowerCase();
  return SEARCHABLE_ICONS.filter(
    (icon) => icon.name.toLowerCase().includes(q) || icon.slug.toLowerCase().includes(q)
  );
}
